def _passphrase() -> bytes:
    """Парольная фраза из окружения, иначе встроенная по умолчанию."""
    env = os.environ.get("OLIVER_FX_KEY")
    return env.encode("utf-8") if env else DEFAULT_PASSPHRASE


def _derive(salt: bytes) -> tuple[bytes, bytes]:
    material = hashlib.scrypt(_passphrase(), salt=salt, n=SCRYPT_N, r=SCRYPT_R,
                              p=SCRYPT_P, dklen=DKLEN, maxmem=SCRYPT_MAXMEM)
    return material[:32], material[32:]


def _keystream(key: bytes, nonce: bytes, length: int) -> bytes:
    """CTR-поток на HMAC-SHA256 как PRF."""
    out, counter = bytearray(), 0
    while len(out) < length:
        out += hmac.new(key, nonce + counter.to_bytes(8, "big"),
                        hashlib.sha256).digest()
        counter += 1
    return bytes(out[:length])


def _xor(data: bytes, stream: bytes) -> bytes:
    return bytes(a ^ b for a, b in zip(data, stream))


def _tag(mac_key: bytes, salt: bytes, nonce: bytes, ct: bytes) -> str:
    return hmac.new(mac_key,
                    MAGIC + salt + nonce + len(ct).to_bytes(8, "big") + ct,
                    hashlib.sha256).hexdigest()


def _unseal() -> bytes:
    """Проверяет MAC, расшифровывает, сверяет SHA-256 открытого текста."""
    salt = base64.b64decode(SALT_B64)
    nonce = base64.b64decode(NONCE_B64)
    ciphertext = base64.b64decode(PAYLOAD_B64)
    enc_key, mac_key = _derive(salt)

    if not hmac.compare_digest(_tag(mac_key, salt, nonce, ciphertext), MAC_TAG):
        raise SystemExit("[fx] MAC контейнера не сходится: файл изменён или "
                         "парольная фраза не та")

    plain = _xor(ciphertext, _keystream(enc_key, nonce, len(ciphertext)))
    if not hmac.compare_digest(hashlib.sha256(plain).hexdigest(), PLAIN_SHA256):
        raise SystemExit("[fx] хеш расшифрованного кода не совпал")
    return plain


def _load_module() -> types.ModuleType:
    """Исполняет проверенный payload в отдельном пространстве имён."""
    source = _unseal().decode("utf-8")
    name = "oliver_fx_sealed"
    module = types.ModuleType(name)
    module.__dict__["__name__"] = name
    module.__dict__["__file__"] = "<sealed:%s>" % SIGNATURE
    # Исполняем только тот код, чью подпись и хеш мы уже проверили выше.
    exec(compile(source, module.__dict__["__file__"], "exec"), module.__dict__)
    sys.modules[name] = module
    return module


def _rebuild(plain_path: str) -> int:
    """Перешифровать контейнер текущей парольной фразой (OLIVER_FX_KEY)."""
    with open(plain_path, "rb") as fh:
        data = fh.read()
    digest = hashlib.sha256(data).hexdigest()
    salt, nonce = os.urandom(16), os.urandom(16)
    enc_key, mac_key = _derive(salt)
    ct = _xor(data, _keystream(enc_key, nonce, len(data)))
    tag = _tag(mac_key, salt, nonce, ct)
    packed = "\n".join('    "%s"' % chunk for chunk in
                       textwrap.wrap(base64.b64encode(ct).decode(), 76))

    me = os.path.abspath(__file__)
    with open(me, "r", encoding="utf-8") as fh:
        src = fh.read()
    head, sep, rest = src.partition("PLAIN_SHA256 = ")
    if not sep:
        raise SystemExit("[fx] не нашёл блок констант — файл повреждён")
    _, sep2, tail = rest.partition("\n\n\ndef _passphrase")
    if not sep2:
        raise SystemExit("[fx] не нашёл конец блока констант")
    new = (head
           + 'PLAIN_SHA256 = "%s"\n' % digest
           + 'SALT_B64 = "%s"\n' % base64.b64encode(salt).decode()
           + 'NONCE_B64 = "%s"\n' % base64.b64encode(nonce).decode()
           + 'MAC_TAG = "%s"\n' % tag
           + "PAYLOAD_B64 = (\n" + packed + "\n)\n\n\ndef _passphrase"
           + tail)
    tmp = me + ".tmp"
    with open(tmp, "w", encoding="utf-8") as fh:
        fh.write(new)
    os.chmod(tmp, 0o600)
    os.replace(tmp, me)
    print("[fx] контейнер перешифрован; SHA-256 payload: %s" % digest)
    return 0


def main(argv: list[str] | None = None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    if argv and argv[0] == "--rebuild":
        if len(argv) != 2:
            raise SystemExit("[fx] использование: --rebuild <открытый .py>")
        return _rebuild(argv[1])
    if argv and argv[0] == "--verify":
        _unseal()
        print("[fx] %s: подпись и хеш в порядке" % SIGNATURE)
        return 0
    print("[fx] %s: контейнер проверен, запускаю рендер" % SIGNATURE)
    return int(_load_module().main(argv))


if __name__ == "__main__":
    sys.exit(main())
