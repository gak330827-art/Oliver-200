 *  Зачем он существует:
 *      · когда заставка молча уходит в главный экран, надо уметь отделить
 *        «контейнер не открылся» от «отвалился синтезатор речи» — здесь
 *        тексты лежат открыто и заведомо читаются;
 *      · при смене текстов сначала правится этот файл, потом
 *        `java tools/SealBrand.java` перепечатывает контейнер, и тест
 *        сверяет оба варианта слово в слово. Рассинхрон роняет сборку —
 *        поэтому «поправил открытый, забыл шифрованный» невозможно.
