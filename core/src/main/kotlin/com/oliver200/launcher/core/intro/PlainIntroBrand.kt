package com.oliver200.launcher.core.intro

object PlainIntroBrand {

    /**
     * Эталон текстов заставки. Ровно эти строки лежат в шифрованном
     * контейнере парного файла — и это проверяется тестом.
     */
    val BRAND = IntroBrand(
        wordmarkTop = "ANIMAL",
        wordmarkBottom = "COMPANY",
        badge = "RU",
        platform = "STEAM COMMUNITY",
        care = "Заботимся о вас",
        voiceRuBrand = "Энимал Компани, Стим Ру.",
        voiceRuCare = "Заботимся о вас.",
        voiceEnBrand = "Animal Company, Steam R U.",
        voiceEnCare = "We take care of you.",
    )

    /**
     * Предохранитель. Вызывать ДО того, как этот вариант что-то отдаст.
     * [debugBuild] должен приходить из BuildConfig.DEBUG.
     */
    @Throws(IntroBrandException::class)
    fun guardRelease(debugBuild: Boolean) {
        if (!debugBuild) {
            throw IntroBrandException(
                "PlainIntroBrand запрещён в release-сборке: заставка обязана идти из шифрованного контейнера",
            )
        }
    }

    /**
     * Тексты прогоняются через кодек, а не отдаются напрямую: путь
     * проверки у открытого и шифрованного вариантов обязан быть один,
     * иначе сюда со временем попадёт строка, которая не пролезла бы
     * через боевой разбор.
     */
    @Throws(IntroBrandException::class)
    fun load(): IntroBrand = IntroBrandCodec.decode(IntroBrandCodec.encode(BRAND))
}
